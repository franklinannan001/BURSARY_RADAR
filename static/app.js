let language = localStorage.getItem("br-language");
if (language !== "sw" && language !== "en") language = "en";
let latestMatchResult = null;
let latestReminderResult = null;

function t(key, values = {}) {
  let text = translations[language][key] || translations.en[key] || key;
  Object.entries(values).forEach(([name, value]) => {
    text = text.replaceAll(`{${name}}`, String(value));
  });
  return text;
}

function applyLanguage() {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-rating]").forEach((node) => {
    node.setAttribute("aria-label", t("feedback.rating", {count: node.dataset.rating}));
  });
  const matchCount = document.querySelector("#matchCount");
  if (matchCount && !latestMatchResult) {
    matchCount.textContent = t("matches.count", {count: 0});
  }
  if (languageToggle) {
    languageToggle.textContent = t(language === "en" ? "language.switch_to_sw" : "language.switch_to_en");
    languageToggle.setAttribute("aria-label", t(language === "en" ? "language.aria_sw" : "language.aria_en"));
  }
  document.dispatchEvent(new Event("br-language-changed"));
}

const languageToggle = document.querySelector("#languageToggle");
if (languageToggle) {
  languageToggle.addEventListener("click", () => {
    language = language === "en" ? "sw" : "en";
    localStorage.setItem("br-language", language);
    applyLanguage();
    renderPlan();
    if (latestMatchResult) {
      const list = document.querySelector("#matchesList");
      list.replaceChildren();
      document.querySelector("#matchCount").textContent = t(
        "matches.count",
        {count: latestMatchResult.likely.length + latestMatchResult.check_eligibility.length}
      );
      renderMatchGroup(t("matches.likely"), latestMatchResult.likely, list);
      renderMatchGroup(t("matches.check"), latestMatchResult.check_eligibility, list);
      if (!latestMatchResult.likely.length && !latestMatchResult.check_eligibility.length) {
        list.textContent = t("matches.empty");
      }
    }
      if (latestReminderResult) {
        loadReminderPreview().catch(() => alert(t("reminder.unavailable")));
      }
  });
}
applyLanguage();

function escapeHtml(value) {
  const node = document.createElement("span");
  node.textContent = value == null ? "" : String(value);
  return node.innerHTML;
}

const opportunityCount = document.querySelector("#opportunityCount");
if (opportunityCount) {
  fetch("/api/opportunities")
    .then((response) => {
      if (!response.ok) throw new Error("Could not load opportunities");
      return response.json();
    })
    .then((opportunities) => {
      opportunityCount.textContent = String(opportunities.length);
    })
    .catch(() => {
      opportunityCount.textContent = "—";
    });
}

const profileForm = document.querySelector("#profileForm");
if (profileForm) {
  let step = 1;
  const titles = ["profile.level", "profile.year", "profile.location", "profile.optional_needs", "profile.review"];
  const studyLevel = document.querySelector("#studyLevelDashboard");
  const studyYear = document.querySelector("#studyYear");
  const countySelect = document.querySelector("#profileCounty");
  const constituencySelect = document.querySelector("#profileConstituency");
  let locations = null;
  let locationsStatus = "loading";

  function setStudyYearOptions(level) {
    const ranges = {
      Primary: [1, 6],
      "Junior Secondary": [1, 3],
      "Senior Secondary": [1, 3],
      Tertiary: [1, 5],
    };
    studyYear.replaceChildren();
    const range = ranges[level];
    if (!range) {
      studyYear.add(new Option(t("profile.select_level"), ""));
      studyYear.disabled = true;
      return;
    }
    studyYear.add(new Option(t("profile.select_year"), ""));
    for (let year = range[0]; year <= range[1]; year += 1) {
      studyYear.add(new Option(t("profile.year_option", {year}), String(year)));
    }
    studyYear.disabled = false;
  }

  const locationsReady = fetch("/static/kenya_locations.json")
    .then((response) => {
      if (!response.ok) throw new Error("Could not load county list");
      return response.json();
    })
    .then((data) => {
      locations = data.counties;
      locationsStatus = "ready";
      countySelect.replaceChildren(new Option(t("profile.select_county"), ""));
      Object.keys(locations).forEach((county) => {
        countySelect.add(new Option(county, county));
      });
      countySelect.disabled = false;
      return true;
    })
    .catch(() => {
      locationsStatus = "failed";
      countySelect.replaceChildren(new Option(t("profile.county_unavailable"), ""));
      countySelect.disabled = true;
      return false;
    });

  function setConstituencyOptions(county) {
    constituencySelect.replaceChildren();
    const constituencies = locations?.[county];
    if (!constituencies) {
      constituencySelect.add(new Option(t("profile.select_county_first"), ""));
      constituencySelect.disabled = true;
      return;
    }
    constituencySelect.add(new Option(t("profile.select_constituency"), ""));
    constituencies.forEach((constituency) => {
      constituencySelect.add(new Option(constituency, constituency));
    });
    constituencySelect.disabled = false;
  }

  studyLevel.addEventListener("change", () => {
    setStudyYearOptions(studyLevel.value);
  });
  countySelect.addEventListener("change", () => {
    setConstituencyOptions(countySelect.value);
  });

  function renderProfileReview() {
    const data = new FormData(profileForm);
    const levelLabels = {
      Primary: "profile.primary",
      "Junior Secondary": "profile.junior",
      "Senior Secondary": "profile.senior",
      Tertiary: "profile.tertiary",
    };
    document.querySelector("#profileReview").innerHTML =
      `<dl><dt>${t("profile.review_level")}</dt><dd>${t(levelLabels[data.get("level")] || "profile.select")}</dd>` +
      `<dt>${t("profile.review_institution")}</dt><dd>${escapeHtml(data.get("institution_name"))}</dd>` +
      `<dt>${t("profile.review_year")}</dt><dd>${escapeHtml(data.get("year_of_study"))}</dd>` +
      `<dt>${t("profile.review_county")}</dt><dd>${escapeHtml(data.get("county"))}</dd>` +
      `<dt>${t("profile.review_constituency")}</dt><dd>${escapeHtml(data.get("constituency"))}</dd></dl>`;
  }

  function showStep(nextStep) {
    step = nextStep;
    document.querySelectorAll(".wizard-step").forEach((node) =>
      node.classList.toggle("active", Number(node.dataset.step) === step)
    );
    document.querySelector("#wizardStep").textContent = String(step);
    document.querySelector("#wizardTitle").textContent = t(titles[step - 1]);
    document.querySelector("#wizardBack").hidden = step === 1;
    document.querySelector("#wizardNext").hidden = step === 5;
    document.querySelector("#wizardSubmit").hidden = step !== 5;
    if (step === 5) renderProfileReview();
  }
  document.addEventListener("br-language-changed", () => {
    document.querySelector("#wizardTitle").textContent = t(titles[step - 1]);
    if (step === 5) renderProfileReview();
    const selectedYear = studyYear.value;
    setStudyYearOptions(studyLevel.value);
    studyYear.value = selectedYear;
    if (!countySelect.value && countySelect.options.length) {
      const countyPlaceholder = {
        loading: "profile.loading_counties",
        ready: "profile.select_county",
        failed: "profile.county_unavailable",
      }[locationsStatus];
      countySelect.options[0].textContent = t(countyPlaceholder);
    }
    if (!constituencySelect.value) setConstituencyOptions(countySelect.value);
  });
  document.querySelector("#wizardNext").addEventListener("click", async () => {
    if (step === 3 && !(await locationsReady)) {
      alert(t("profile.county_unavailable"));
      return;
    }
    const requiredFields = document.querySelectorAll(
      `.wizard-step[data-step="${step}"] [required]`
    );
    for (const field of requiredFields) {
      if (field.disabled) continue;
      if (!field.checkValidity()) {
        field.focus();
        field.reportValidity();
        return;
      }
    }
    showStep(Math.min(5, step + 1));
  });
  document.querySelector("#wizardBack").addEventListener("click", () => showStep(Math.max(1, step - 1)));
  document.querySelector("#sampleButton").addEventListener("click", async () => {
    if (!(await locationsReady)) {
      alert(t("profile.county_unavailable"));
      return;
    }
    profileForm.elements.level.value = "Tertiary";
    setStudyYearOptions("Tertiary");
    profileForm.elements.institution_type.value = "public";
    profileForm.elements.institution_name.value = "Machakos University";
    profileForm.elements.year_of_study.value = "1";
    countySelect.value = "Machakos";
    setConstituencyOptions("Machakos");
    constituencySelect.value = "Mwala";
    showStep(1);
    document.querySelector("#find").scrollIntoView({ behavior: "smooth" });
  });
  profileForm.addEventListener("submit", async (event) => {
    event.preventDefault();
    const data = new FormData(profileForm);
    const profile = {
      level:data.get("level"), institution_type:data.get("institution_type") || null,
      institution_name:data.get("institution_name") || null,
      year_of_study:data.get("year_of_study") ? Number(data.get("year_of_study")) : null,
      county:data.get("county") || null, constituency:data.get("constituency") || null,
      need_flags:data.getAll("need_flag"),
    };
    const list = document.querySelector("#matchesList");
    latestMatchResult = null;
    list.textContent = t("matches.finding");
    try {
      const response = await fetch("/api/match", {method:"POST",headers:{ "Content-Type":"application/json" },body:JSON.stringify(profile)});
      if (!response.ok) throw new Error("Could not match opportunities");
      const result = await response.json();
      latestMatchResult = result;
      list.replaceChildren();
      document.querySelector("#matchCount").textContent = t("matches.count", {count: result.likely.length + result.check_eligibility.length});
      renderMatchGroup(t("matches.likely"), result.likely, list);
      renderMatchGroup(t("matches.check"), result.check_eligibility, list);
      if (!result.likely.length && !result.check_eligibility.length) {
        list.textContent = t("matches.empty");
      }
    } catch {
      list.textContent = t("matches.unavailable");
    }
  });
}

function renderMatchGroup(title, matches, container) {
  if (!matches.length) return;
  const heading = document.createElement("h3");
  heading.className = "match-group-title";
  heading.textContent = title;
  container.appendChild(heading);
  matches.forEach((match) => {
    const opportunity = match.opportunity;
    const additionalDetails = [];
    if (Number.isInteger(opportunity.number_of_bursaries)) {
      additionalDetails.push(t("opportunity.number_bursaries", {
        count: opportunity.number_of_bursaries,
      }));
    }
    if (opportunity.disbursement_start && opportunity.disbursement_end) {
      additionalDetails.push(t("opportunity.disbursement", {
        start: opportunity.disbursement_start,
        end: opportunity.disbursement_end,
      }));
    }
    const card = document.createElement("article");
    card.className = "match-card";
    card.innerHTML =
      `<div class="match-main"><div class="badge-row"><span class="provider-chip">${escapeHtml(opportunity.provider_type.replaceAll("_"," "))}</span><span class="confidence ${opportunity.confidence.toLowerCase()}">${escapeHtml(opportunity.confidence)}</span></div><h3>${escapeHtml(opportunity.name)}</h3><p>${escapeHtml(opportunity.provider)}</p><div class="meta"><span>${escapeHtml(opportunity.deadline || t("opportunity.deadline_unknown"))}</span><span>${escapeHtml(opportunity.amount_note || (opportunity.amount_published ? t("opportunity.amount_published") : t("opportunity.amount_unknown")))}</span>${additionalDetails.map((detail) => `<span>${escapeHtml(detail)}</span>`).join("")}</div><p class="match-reasons">${(match.reasons || []).map((reason) => escapeHtml(translateMatchReason(reason))).join(" • ")}</p><details><summary>${t("opportunity.documents")}</summary><p>${escapeHtml(opportunity.documents_required ? opportunity.documents_required.join(", ") : t("opportunity.documents_unknown"))}</p><p>${escapeHtml(opportunity.how_to_apply || t("opportunity.source_instructions"))}</p></details></div>
       <div class="match-actions"><button class="outline-button plan-button" type="button">${t("opportunity.add")}</button><a class="source-link" href="${escapeHtml(opportunity.apply_url || opportunity.source_url)}" target="_blank" rel="noopener noreferrer">${t("opportunity.source")}</a><button class="outline-button report-button" type="button">${t("opportunity.report")}</button></div>`;
    card.querySelector(".plan-button").addEventListener("click", (event) => addToPlan(opportunity, event.currentTarget));
    card.querySelector(".report-button").addEventListener("click", () => reportOpportunity(opportunity));
    container.appendChild(card);
  });
}

function translateMatchReason(reason) {
  const reasonKeys = {
    "Matched because: level is included": "matches.reason.level",
    "Matched because: institution type is included": "matches.reason.institution_type",
    "Matched because: institution name matches": "matches.reason.institution_name",
    "Matched because: county matches": "matches.reason.county",
    "Matched because: constituency matches": "matches.reason.constituency",
    "Matched because: gender matches": "matches.reason.gender",
    "Check eligibility at the source": "matches.reason.check",
    "Matches the profile supplied": "matches.reason.profile",
  };
  if (reasonKeys[reason]) return t(reasonKeys[reason]);
  const needsMatch = reason.match(/^Matched because: (.+) support applies$/);
  if (needsMatch) {
    const needKeys = {
      orphan: "profile.orphan",
      disability: "profile.disability",
      low_income: "profile.low_income",
      single_parent: "profile.single_parent",
    };
    const needs = needsMatch[1].split(", ").map((need) => t(needKeys[need] || need)).join(", ");
    return t("matches.reason.support", {needs});
  }
  return reason;
}

function getPlan() {
  try { return JSON.parse(localStorage.getItem("bursary-radar-plan") || "[]"); }
  catch { return []; }
}

function addToPlan(opportunity, button) {
  const plan = getPlan();
  const exists = plan.some((item) => item.id === opportunity.id);
  if (!exists) { plan.push(opportunity); localStorage.setItem("bursary-radar-plan", JSON.stringify(plan)); }
  button.textContent = exists ? t("opportunity.already_added") : t("opportunity.added");
  button.classList.remove("button-success","button-added");
  void button.offsetWidth;
  button.classList.add(exists ? "button-added" : "button-success");
  renderPlan();
  window.setTimeout(() => { button.textContent = t("opportunity.add"); button.classList.remove("button-success","button-added"); }, 2400);
}

function renderPlan() {
  const plan = getPlan();
  const summary = document.querySelector("#planSummary");
  const list = document.querySelector("#planList");
  if (!summary || !list) return;
  summary.textContent = plan.length ? (plan.length === 1 ? t("plan.summary_one") : t("plan.summary", {count: plan.length})) : t("plan.empty");
  list.innerHTML = "";
  plan.forEach((opportunity) => {
    const item = document.createElement("article");
    item.className = "plan-item";
    item.innerHTML = `<strong>${escapeHtml(opportunity.name)}</strong><span>${escapeHtml(opportunity.deadline || t("opportunity.deadline_unknown"))}</span>`;
    list.appendChild(item);
  });
}
renderPlan();

